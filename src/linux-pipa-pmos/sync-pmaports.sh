#!/bin/bash
# sync-pmaports.sh - refresh this PKGBUILD from postmarketOS pmaports (linux-xiaomi-pipa)
#
#   ./sync-pmaports.sh            update version, patches, config and checksums
#   ./sync-pmaports.sh --check    only report whether pmaports differs (exit 10 = update available)
#
# Env:  PMAPORTS_DIR=/path/to/local/pmaports   use a local clone/extract instead of cloning
#       PMAPORTS_URL=...  PMAPORTS_REF=...     other repo / branch / tag
#       PMOS_PKG=linux-xiaomi-pipa             package folder name to look for
#
# It never sources the APKBUILD (text parsing only) and it stops on anything unexpected
# instead of guessing. Review `git diff`/the printed summary, then run makepkg yourself.
set -euo pipefail
cd "$(dirname "$(readlink -f "$0")")"

REPO=${PMAPORTS_URL:-https://gitlab.postmarketos.org/postmarketOS/pmaports.git}
PKG=${PMOS_PKG:-linux-xiaomi-pipa}
CHECK=0; [[ ${1:-} == --check ]] && CHECK=1
BEGIN='# >>> pmaports-sync: generated by sync-pmaports.sh, do not edit >>>'
END='# <<< pmaports-sync <<<'
die() { echo "sync-pmaports: $*" >&2; exit 1; }

# ---- 1. get the pmaports folder -------------------------------------------------------
if [[ -n ${PMAPORTS_DIR:-} ]]; then
    src=$(cd "$PMAPORTS_DIR" && find . -path "*/$PKG/APKBUILD" | head -n1 || true)
    [[ -n $src ]] || die "no $PKG/APKBUILD under $PMAPORTS_DIR"
    src=$(cd "$PMAPORTS_DIR/$(dirname "$src")" && pwd)
else
    tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
    echo "Cloning $REPO (shallow, no file contents yet)..."
    git clone --quiet --depth 1 --filter=blob:none --no-checkout \
        ${PMAPORTS_REF:+--branch "$PMAPORTS_REF"} "$REPO" "$tmp/pm"
    apk=$(git -C "$tmp/pm" ls-tree -r --name-only HEAD | grep -E "(^|/)$PKG/APKBUILD$" | head -n1 || true)
    [[ -n $apk ]] || die "$PKG/APKBUILD not found in $REPO (renamed or removed upstream?)"
    git -C "$tmp/pm" sparse-checkout set --no-cone "/$(dirname "$apk")/"
    git -C "$tmp/pm" checkout --quiet
    src=$tmp/pm/$(dirname "$apk")
    echo "Found $(dirname "$apk")"
fi
APKBUILD=$src/APKBUILD

# ---- 2. parse the APKBUILD (text only) ------------------------------------------------
pkgver=$(sed -n 's/^pkgver="\?\([^"]*\)"\?$/\1/p' "$APKBUILD" | head -n1)
flavor=$(sed -n 's/^_flavor="\?\([^"]*\)"\?$/\1/p' "$APKBUILD" | head -n1)
[[ $pkgver =~ ^[0-9]+(\.[0-9]+)+$ ]] || die "cannot read pkgver (got '$pkgver')"
[[ -n $flavor ]] || die "cannot read _flavor"

# block between source=" and the closing quote
mapfile -t entries < <(awk '
    /^source="/ {f=1; sub(/^source="/,"")}
    f { end = ($0 ~ /"[[:space:]]*$/); sub(/"[[:space:]]*$/,""); gsub(/^[ \t]+|[ \t]+$/,""); if ($0!="") print; if (end) exit }
' "$APKBUILD")
((${#entries[@]})) || die "empty/unparsable source= block"

declare -A sum
while read -r h n; do [[ $h =~ ^[0-9a-f]{128}$ && -n $n ]] && sum[$n]=$h; done < <(
    awk '/^sha512sums="/{f=1; sub(/^sha512sums="/,"")} f{end=($0 ~ /"[[:space:]]*$/); sub(/"[[:space:]]*$/,""); if($0!="")print; if(end)exit}' "$APKBUILD")

files=(); tar_ok=0
for e in "${entries[@]}"; do
    major=${pkgver%%.*}
    e=${e//'${pkgver%%.*}'/$major}; e=${e//'${pkgver}'/$pkgver}
    e=${e//'$pkgver'/$pkgver}; e=${e//'$_flavor'/$flavor}
    if [[ $e == *::* ]]; then
        [[ $e == "linux-$pkgver.tar.xz::https://cdn.kernel.org/pub/linux/kernel/v${pkgver%%.*}.x/linux-$pkgver.tar.xz" ]] \
            || die "kernel tarball source changed ($e); update the PKGBUILD source=() URL by hand"
        tar_ok=1; continue
    fi
    [[ $e =~ ^[A-Za-z0-9._+-]+$ ]] || die "unexpected source entry: $e"
    case $e in
        config-*|*.patch) files+=("$e") ;;
        *) die "new kind of source file '$e'; extend sync-pmaports.sh / the PKGBUILD" ;;
    esac
done
((tar_ok)) || die "no kernel tarball entry in source="
tar_sum=${sum["linux-$pkgver.tar.xz"]:-}; [[ -n $tar_sum ]] || die "no checksum for linux-$pkgver.tar.xz"

cfg=(); patches=()
for f in "${files[@]}"; do [[ $f == config-* ]] && cfg+=("$f") || patches+=("$f"); done
((${#cfg[@]}==1)) || die "expected exactly 1 config file, got ${#cfg[@]}"
((${#patches[@]})) || die "no patches listed (kernel vanilla upstream now? PKGBUILD may need changing)"
ordered=("${cfg[@]}" "${patches[@]}")

for f in "${ordered[@]}"; do
    [[ -f $src/$f ]] || die "$f listed in APKBUILD but missing in the repo"
    [[ -n ${sum[$f]:-} ]] || die "no checksum for $f"
    [[ $(sha512sum "$src/$f" | cut -d' ' -f1) == "${sum[$f]}" ]] || die "checksum mismatch for $f"
done

# ---- 3. build the new generated block --------------------------------------------------
new=$(
    echo "pkgver=$pkgver"
    echo "_tar_sum='$tar_sum'"
    echo "_pmos_files=("; for f in "${ordered[@]}"; do echo "    '$f'"; done; echo ")"
    echo "_pmos_sums=(";  for f in "${ordered[@]}"; do echo "    '${sum[$f]}'"; done; echo ")"
)
old=$(awk -v b="$BEGIN" -v e="$END" '$0==b{f=1;next} $0==e{f=0} f' PKGBUILD)
grep -qxF "$BEGIN" PKGBUILD && grep -qxF "$END" PKGBUILD || die "generated-block markers missing in PKGBUILD"

oldver=$(sed -n 's/^pkgver=//p' <<<"$old")
echo "pmaports: $PKG $pkgver (${#patches[@]} patches)   local: ${oldver:-none}"

prev=(); [[ -f .pmaports-managed ]] && mapfile -t prev < .pmaports-managed
dirty=0
for f in "${ordered[@]}"; do
    if [[ ! -f $f ]]; then echo "  + $f"; dirty=1
    elif ! cmp -s "$src/$f" "$f"; then echo "  ~ $f"; dirty=1; fi
done
for f in "${prev[@]}"; do
    [[ " ${ordered[*]} " == *" $f "* ]] || { echo "  - $f (dropped upstream)"; dirty=1; }
done
if [[ $new == "$old" && $dirty == 0 ]]; then echo "Already up to date."; exit 0; fi
if ((CHECK)); then echo "Update available."; exit 10; fi

# ---- 4. apply --------------------------------------------------------------------------
for f in "${prev[@]}"; do
    [[ " ${ordered[*]} " == *" $f "* ]] || rm -f -- "$f"      # only files we put there before
done
for f in "${ordered[@]}"; do cp -- "$src/$f" "$f"; done
printf '%s\n' "${ordered[@]}" > .pmaports-managed

tmpf=$(mktemp)
awk -v b="$BEGIN" -v e="$END" -v n="$new" '
    $0==b {print; print n; skip=1; next}
    $0==e {skip=0}
    !skip {print}' PKGBUILD > "$tmpf"
cat "$tmpf" > PKGBUILD; rm -f "$tmpf"

# pkgrel: reset on a new kernel version, +1 when only patches/config changed (not on first run)
if [[ $new != "$old" ]] && grep -q '^_pmos_files=' <<<"$old"; then
    cur=$(sed -n 's/^pkgrel=//p' PKGBUILD | head -n1)
    if [[ ${oldver:-} != "$pkgver" ]]; then rel=1; else rel=$((cur+1)); fi
    sed -i "s/^pkgrel=.*/pkgrel=$rel/" PKGBUILD
    echo "pkgrel -> $rel"
fi
echo "Updated. Review the changes, then: makepkg -sf"
